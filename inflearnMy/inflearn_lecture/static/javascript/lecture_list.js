$(function () {
  $('.row').hide()
  $('#all_lecture').show()

  $('#hot_lecture_menu').click(function () {
    $('.row').hide()
    $('#hot_lecture').show()
  })
  $('#all_lecture_menu').click(function () {
    $('.row').hide()
    $('#all_lecture').show()
  })
  $('#html_lecture_menu').click(function () {
    $('.row').hide()
    $('#html_lecture').show()
  })
  $('#css_lecture_menu').click(function () {
    $('.row').hide()
    $('#css_lecture').show()
  })
  $('#javascript_lecture_menu').click(function () {
    $('.row').hide()
    $('#javascript_lecture').show()
  })
})
